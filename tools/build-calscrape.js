// Builds apps-script/CalendarScrape.gs: the calendar parser copied verbatim from
// index.html (between its "begin parser"/"end parser" markers) + apps-script/calscrape/main.gs.
// Run: node tools/build-calscrape.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');

function build() {
  const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8').split('\n');
  const start = html.findIndex(l => l.startsWith('const CAL_SHIFT_RE'));
  const end = html.findIndex(l => l.includes('// ===== end parser ====='));
  if (start < 0 || end < 0 || end < start) throw new Error('parser markers not found in index.html');
  const parser = html.slice(start, end + 1).join('\n');
  const main = fs.readFileSync(path.join(root, 'apps-script/calscrape/main.gs'), 'utf8');
  const header = '// GENERATED by tools/build-calscrape.js. Edit index.html parser or apps-script/calscrape/main.gs, then rebuild.\n';
  return header + parser + '\n\n' + main;
}

// Node copy of the parser for the Cloud Functions (functions/calparser.js).
function buildNode() {
  const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8').split('\n');
  const start = html.findIndex(l => l.startsWith('const CAL_SHIFT_RE'));
  const end = html.findIndex(l => l.includes('// ===== end parser ====='));
  if (start < 0 || end < 0 || end < start) throw new Error('parser markers not found in index.html');
  return '// GENERATED by tools/build-calscrape.js from index.html. Do not edit.\n' +
    html.slice(start, end + 1).join('\n') +
    '\nmodule.exports = { calParseEmail, calParseRow, calIsoOf, calCells, calShiftBase };\n';
}

if (require.main === module) {
  const out = path.join(root, 'apps-script/CalendarScrape.gs');
  fs.writeFileSync(out, build());
  console.log('wrote', out);
  const node = path.join(root, 'functions/calparser.js');
  fs.writeFileSync(node, buildNode());
  console.log('wrote', node);
}

module.exports = { build, buildNode };
